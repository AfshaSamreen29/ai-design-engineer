import { readFileSync, lstatSync } from "node:fs";
import path from "node:path";
import {
  createDefaultDesignSystem,
  parseDesignSystemJson,
  toCss,
  toJson,
  type DesignSystem,
} from "@ai-design-engineer/design-tokens";
import { SKILL_DIR, SKILL_NAME, listSkillFiles } from "@ai-design-engineer/skills";
import { generateBrief, slugify, clean } from "./brief.ts";
import { CliError } from "./errors.ts";
import { resolveInside, type FileSpec } from "./fsafe.ts";
import { commitFiles, flag, str, type Ctx } from "./context.ts";

const DEFAULT_DS_PATH = "design/design-system.json";

function limit(ctx: Ctx, name: string, max: number): string | undefined {
  const v = str(ctx, name);
  if (v === undefined) return undefined;
  const c = clean(v);
  // eslint-disable-next-line no-control-regex
  if (c.length > max || /[\u0000-\u0008\u000b\u000c\u000e-\u001f]/.test(v)) {
    throw new CliError(`--${name} must be at most ${max} characters and contain no control characters.`, 2);
  }
  return c;
}

function readTextInside(ctx: Ctx, rel: string): string | null {
  const abs = resolveInside(ctx.root, rel);
  try {
    if (!lstatSync(abs).isFile()) throw new CliError(`"${rel}" is not a file.`);
  } catch (e) {
    if (e instanceof CliError) throw e;
    return null;
  }
  return readFileSync(abs, "utf8");
}

function loadDesignSystem(ctx: Ctx, explicit: string | undefined): { ds: DesignSystem; isDefault: boolean } {
  const rel = explicit ?? DEFAULT_DS_PATH;
  const text = readTextInside(ctx, rel);
  if (text === null) {
    if (explicit) throw new CliError(`Design system file not found: ${rel}`);
    return { ds: createDefaultDesignSystem(), isDefault: true };
  }
  const result = parseDesignSystemJson(text);
  if (!result.ok) {
    const details = result.errors.map((e) => `  - ${e.path || "(file)"} ${e.message}`).join("\n");
    throw new CliError(`Invalid design system in ${rel}:\n${details}`);
  }
  return { ds: result.value, isDefault: false };
}

const buf = (s: string) => Buffer.from(s, "utf8");

// ---------------------------------------------------------------- init
export function initCommand(ctx: Ctx): number {
  const name = limit(ctx, "name", 80) ?? path.basename(ctx.root);
  const ds = createDefaultDesignSystem({ id: slugify(name), name: `${name} design system`.slice(0, 80) });

  const config = {
    version: 1,
    project: { name },
    designSystem: DEFAULT_DS_PATH,
    brief: "design/DESIGN_BRIEF.md",
    tokensOutput: "design/tokens",
  };

  const instructions = `# Design instructions for ${name}

Generated by \`ai-design-engineer init\` from a template. No AI model was used. Edit freely.

## Source of truth
- Design tokens: \`${DEFAULT_DS_PATH}\`. Export CSS and JSON with \`ai-design-engineer tokens export\`.
- Design brief: \`design/DESIGN_BRIEF.md\` (create with \`ai-design-engineer design\`).

## Rules for coding agents
1. Read the design brief and tokens before changing any UI.
2. Use token values for color, type, spacing, radius, and shadow. Do not hard-code new ones.
3. Write real, specific copy. Never invent testimonials, customer logos, statistics, or awards.
4. Build mobile first and check 375, 768, and 1440 px wide.
5. Keep semantic HTML, visible keyboard focus, and reduced-motion support.
6. Look at the rendered page before saying the work is finished, and report what was and was not verified.

If the \`${SKILL_NAME}\` skill is installed, follow it for landing pages (\`ai-design-engineer skill install\`).
`;

  const files: FileSpec[] = [
    { path: "ai-design-engineer.config.json", content: buf(JSON.stringify(config, null, 2) + "\n") },
    { path: DEFAULT_DS_PATH, content: buf(toJson(ds)) },
    { path: "design/AGENT_INSTRUCTIONS.md", content: buf(instructions) },
  ];
  const code = commitFiles(ctx, files);
  if (code === 0 && !flag(ctx, "dry-run")) {
    ctx.io.out("Next: edit design/design-system.json, then run `ai-design-engineer design` and `ai-design-engineer tokens export`.");
  }
  return code;
}

// -------------------------------------------------------------- design
export function designCommand(ctx: Ctx): number {
  const input = {
    name: limit(ctx, "name", 80),
    type: limit(ctx, "type", 120),
    audience: limit(ctx, "audience", 300),
    goal: limit(ctx, "goal", 300),
    description: limit(ctx, "description", 600),
  };
  const { ds, isDefault } = loadDesignSystem(ctx, str(ctx, "input"));
  const out = str(ctx, "out") ?? "design/DESIGN_BRIEF.md";
  return commitFiles(ctx, [{ path: out, content: buf(generateBrief(input, ds, isDefault)) }]);
}

// ------------------------------------------------------- tokens export
export function tokensExportCommand(ctx: Ctx): number {
  const format = str(ctx, "format") ?? "both";
  if (!["json", "css", "both"].includes(format)) {
    throw new CliError(`--format must be json, css, or both (got "${format}").`, 2);
  }
  const { ds } = loadDesignSystem(ctx, str(ctx, "input") ?? undefined);
  const outDir = (str(ctx, "out") ?? "design/tokens").replace(/[\\/]+$/, "");
  const files: FileSpec[] = [];
  if (format !== "css") files.push({ path: `${outDir}/tokens.json`, content: buf(toJson(ds)) });
  if (format !== "json") files.push({ path: `${outDir}/tokens.css`, content: buf(toCss(ds)) });
  return commitFiles(ctx, files);
}

// -------------------------------------------------------- skill install
const TARGETS: Record<string, string> = {
  claude: `.claude/skills/${SKILL_NAME}`,
  agents: `docs/skills/${SKILL_NAME}`,
  codex: `docs/skills/${SKILL_NAME}`,
};

export function skillInstallCommand(ctx: Ctx): number {
  const target = str(ctx, "target") ?? "claude";
  const dest = (str(ctx, "dest") ?? (Object.hasOwn(TARGETS, target) ? TARGETS[target] : undefined))?.replace(/[\\/]+$/, "");
  if (!dest) {
    throw new CliError(`Unknown --target "${target}". Use one of: ${Object.keys(TARGETS).join(", ")}, or pass --dest <folder>.`, 2);
  }
  const files: FileSpec[] = listSkillFiles().map((rel) => ({
    path: `${dest}/${rel}`,
    content: readFileSync(path.join(SKILL_DIR, ...rel.split("/"))),
  }));
  const code = commitFiles(ctx, files);
  if (code === 0 && !flag(ctx, "dry-run") && (target === "agents" || target === "codex")) {
    ctx.io.out(`Add this line to AGENTS.md: "For landing pages, read and follow ${dest}/SKILL.md before writing code."`);
  }
  return code;
}

